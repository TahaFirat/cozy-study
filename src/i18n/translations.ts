export function getRoomTranslation(lang: Language, roomId: RoomId): { name: string; subtitle: string; desc: string } {
  const roomKey = roomId as 'bedroom' | 'apartment' | 'cabin' | 'library' | 'cafe' | 'kyoto_zen' | 'cyberpunk_loft';
  return TRANSLATIONS[lang].rooms[roomKey] || TRANSLATIONS[lang].rooms.bedroom;
}
